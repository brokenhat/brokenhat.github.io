Woven in one long strip and then stitched together to create spatial form of riband.

It was made like that to highlight the technique of stitching together multiple strips of kilim to create larger one — as seen in multiple examples from weaving culture from the middle east — usually used as floor covering or wrap for other more precious textiles.

This one is especially inspired by mazandaran and jajim kilims from northern Iran.


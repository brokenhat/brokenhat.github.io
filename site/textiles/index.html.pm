£section-intro{
Untitled, 2024

2 sets of interwoven warp - woven from the back and from the "front", constantly rotating the frame back and forth and by 90 deg angle.The frame itself was just regular stretcher used for paintings. See the photos below from the process.

Apart from interplay between the warps this tapestry uses also pile knotted parts( using only persian knots ) and then trimmed into sculptural form to match abstract whole.
}

£section-intro{
blue stem

Handwoven tapestry.

Wool on wool.

Woven in one long strip and then stiched together to create spatial form of riband.

It was made like that to highlight the technique of stiching together multiple strips of kilim to create larger one -

- usually used as floor covering or wrap for other more precious textiles in persian culture and within tribes of Caucasus.

This one is especially inspired by mazandaran and jajim kilims.

approx 200cm high.
}


2 sets of interwoven warp — woven from the back and from the front, constantly rotating the frame back and forth and by 90 degree angle. The frame itself was just regular stretcher used for paintings.

Apart from interplay between the warps this tapestry uses also pile knotted parts (using only persian knots) and then trimmed into sculptural form to match abstract whole.


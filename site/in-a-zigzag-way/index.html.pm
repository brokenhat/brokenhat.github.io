In my first solo exhibition,
I explore the zigzag as a primal leitmotif.
Through a collection of textiles and paintings,
these works trace the jagged energy that once gave life to
countless expressive kilims, rugs, and tapestries.

£strong{When:} 08.09.2026 – 18.09.2026, 10am – 5pm

£strong{Where:} Out of the Blue Drill Hall, 36 Dalmeny Street, Edinburgh EH6 8RG

£strong{Opening reception:} 07.09.2026, 6pm – 8pm, free entry

a zigzag is a loud pause.
a zigzag stands in the middle of a field,
opposing the horizon like a lonely Scottish standing stone.

a zigzag is a symbol of force
always moving
through the tacky medium of sweaty threads.

a zigzag is the track a child follows.

a zigzag is a rhythmic word that zaps magically into place,
just like an incantation.

a zigzag is a geological action — a tectonic shift cracking stones.

a zigzag is a lightning bolt —
cutting through the stifling weight of a summer storm.

a zigzag is the upward movement of improvisation,
the way tapestries live.

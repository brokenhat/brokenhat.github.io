£section-intro{

My artistic practice is a blend of conceptuality and multidisciplinarity. I find myself drawn to exploring diverse means and methods of artistic expression, which allows me to constantly challenge and reinvent myself.

One of my favorite approaches is to consider visual arts and music in parallel, finding a deep connection between the two. In fact, it feels as though they are entangled in my mind, equally inspiring my creations. An important project in my journey was Syncopes, where I created abstract rules to translate sections of musical forms and genres into visual representations.

Throughout my education, I developed certain mannerisms, especially from learning the foundations of figurative art. While some artists try to escape or forget these habits, I consciously overthink and reflect on them in my work. This allows me to strike a balance between the past and the future, engaging in a continuous dialogue with both traditional and modern art.

Recently, I have been enthralled by the world of weaving, particularly tapestry weaving and its related forms. To me, weaving has a slow-paced, minimalistic melody, the rhythmic motion and the constant movement of the loom become an integral part of my creative process, infusing my work with a unique artistic expression.


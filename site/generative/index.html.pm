£section-intro{
Generative art holds special place in my practice.

It is very different form of creating things. Usually artist deals with the physical or virtual matter itself, should have almost total control over the piece. In the contrary generative art puts rules and algorithms( recipes ) in the first place. Here I have to define definitions for future outcome, in that sense it is possible to create artificial environments( usually very simplistic one) in which I can pull a slice of it from and make it visible. In that way at moments I can generate several slices all different to each other but similar in the light of the recipe. Below You will find a couple of them.

From the techical perspective these are made using Clojure functional language and its Quil library( which is based on Processing) Have a look at the essays of Tyler Hobbs - tylerxhobbs.com to have better understanding of what is going on here. Also recommend looking at the possibilities of generative art here( from Jared Tarbell complexification.net/gallery/ )
}

